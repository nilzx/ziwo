/**
 * format fills the {placeholders} of a text. A placeholder without a value
 * is left as it is, so that a missing value shows.
 * @param {string} text
 * @param {Record<string, string | number>} [vars]
 */
export function format(text, vars = {}) {
  return text.replace(/\{([a-zA-Z]+)\}/g, (whole, k) => (k in vars ? String(vars[k]) : whole));
}
