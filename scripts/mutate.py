env = dict(os.environ)
only = sys.argv[1:]  # optional substrings to select mutations
missed = []
for name, path, old, new in MUTATIONS:
    if only and not any(o in name for o in only):
        continue
    full = os.path.join(REPO, path)
    src = open(full).read()
    if src.count(old) != 1:
        print(f"SKIP  {name}: target occurs {src.count(old)} times in {path}")
        missed.append(name)
        continue
    shutil.copy(full, full + ".orig")
    try:
        open(full, "w").write(src.replace(old, new))
        r = subprocess.run(["go", "test", "-tags", "sqlite_fts5", "./..."], cwd=REPO, env=env,
                           capture_output=True, text=True)
        out = r.stdout + r.stderr
        if r.returncode == 0:
            print(f"MISSED  {name}")
            missed.append(name)
        elif "[build failed]" in out or "cannot" in out and "FAIL:" not in out:
            print(f"BUILD?  {name}\n{out[-600:]}")
            missed.append(name)
        else:
            failed = sorted({l.split()[2] for l in out.splitlines() if l.startswith("--- FAIL")})
            print(f"caught  {name}: {', '.join(failed[:4])}{' …' if len(failed) > 4 else ''}")
    finally:
        shutil.move(full + ".orig", full)
print("\nnot caught:", missed if missed else "none")
sys.exit(1 if missed else 0)
